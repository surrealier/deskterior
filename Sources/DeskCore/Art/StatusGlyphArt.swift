/// The menu-bar status item's glyph (DESIGN §4.9): a monitor with a few desktop icons, standing on a desk — black
/// and alpha only, so AppKit tints it as a template image for light and dark menu bars. Drawn pixel for pixel at
/// 18×18 pt, once for 1× and again for 2× (rounded corners, dog-eared icons, a power button), never scaled.
public enum StatusGlyphArt {
    /// The glyph's size in points.
    public static let points = 18

    /// The glyph at `scale` (1 or 2) as black pixels on clear: `points × scale` px square.
    public static func image(scale: Int) -> PixelBuffer {
        let art = scale >= 2 ? art2x : art1x
        let rows = art.split(separator: "\n")
        let n = points * (scale >= 2 ? 2 : 1)
        precondition(rows.count == n && rows.allSatisfy { $0.count == n }, "StatusGlyphArt: bad \(scale)x art")
        var out = PixelBuffer(width: n, height: n)
        for (y, row) in rows.enumerated() {
            for (x, ch) in row.enumerated() where ch == "#" { out[x, y] = ink }
        }
        return out
    }

    /// Template ink: opaque black (only the alpha matters to AppKit).
    public static let ink = RGBA8(0, 0, 0, 255)

    /// 1× source (`#` ink, `.` clear).
    static let art1x = """
        ..................
        .################.
        .#..............#.
        .#.##.##.##.....#.
        .#.##.##.##.....#.
        .#..............#.
        .#.##.##........#.
        .#.##.##........#.
        .#..............#.
        .################.
        .################.
        ........##........
        ......######......
        ##################
        ##################
        .#..............#.
        .#..............#.
        .#..............#.
        """

    /// 2× source, drawn on its own grid.
    static let art2x = """
        ....................................
        ....................................
        ...##############################...
        ..################################..
        ..##............................##..
        ..##............................##..
        ..##...###...###...###..........##..
        ..##...####..####..####.........##..
        ..##...####..####..####.........##..
        ..##...####..####..####.........##..
        ..##............................##..
        ..##............................##..
        ..##...###...###................##..
        ..##...####..####...............##..
        ..##...####..####...............##..
        ..##...####..####...............##..
        ..##............................##..
        ..##............................##..
        ..################################..
        ..##########################..####..
        ..##########################..####..
        ...##############################...
        ................####................
        ................####................
        ............############............
        .............##########.............
        ####################################
        ####################################
        ####################################
        .##################################.
        ..##............................##..
        ..##............................##..
        ..##............................##..
        ..##............................##..
        ..##............................##..
        ..##............................##..
        """
}
